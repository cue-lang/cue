//go:build ignore

// Generate types_gen.go: the open per-encoding data structures that
// the fixed unification driver in unify.go resolves file types over.
//
// The generator evaluates types.cue — the single source of truth —
// with the real CUE evaluator and emits every mode base, extension,
// encoding, top-level tag, form, and interpretation entry as a
// readable Go composite literal, recording per-field default-ness
// (unset / default / concrete) so that unification can be executed
// field-wise at runtime. Subsidiary-tag default cascades such as
// "strictKeywords: *strict | bool" are recorded as references and
// resolved after unification, preserving the semantics of the
// previously generated per-combination functions.
package main

import (
	"bytes"
	"fmt"
	goformat "go/format"
	"log"
	"maps"
	"os"
	"slices"
	"strings"

	"cuelang.org/go/cue"
	"cuelang.org/go/cue/ast"
	"cuelang.org/go/cue/cuecontext"
	cueformat "cuelang.org/go/cue/format"
	"cuelang.org/go/cue/token"
	"cuelang.org/go/internal/filetypes"
)

func main() {
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

// The tri-state kinds of the driver's sval/bval representation,
// mirrored here so extraction can be expressed independently of the
// filetypes package internals.
type kind uint8

const (
	unset kind = iota
	constraint
	dflt
	concrete
	ref
)

type sval struct {
	kind     kind
	value    string
	domain   []string // closed disjunction domain; nil is open
	excluded []string
}

type bval struct {
	kind      kind
	value     bool
	reference string // reference target when kind == ref
}

var aspectNames = []string{
	"attributes", "constraints", "cycles", "data", "definitions", "docs",
	"incomplete", "imports", "keepDefaults", "optional", "references", "stream",
}

// entry mirrors the driver's entry type in extractable form.
type entry struct {
	encoding       sval
	interpretation sval
	form           sval
	aspects        map[string]bval
	boolTags       map[string]bval
	tags           map[string]sval
	alts           []*entry
}

var modeNames = []string{"input", "export", "def", "eval"}

func generate() error {
	typesCUE, err := os.ReadFile("types.cue")
	if err != nil {
		return err
	}
	ctx := cuecontext.New()
	rootVal := ctx.CompileBytes(typesCUE, cue.Filename("types.cue"))
	if err := rootVal.Err(); err != nil {
		return err
	}
	if err := rootVal.Validate(cue.All()); err != nil {
		return fmt.Errorf("validating types.cue: %w", err)
	}
	if err := validateFileInfoSchema(rootVal); err != nil {
		return err
	}
	if err := validateExtractorGuards(ctx); err != nil {
		return err
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cuelang.org/go/internal/filetypes/generate.go from types.cue. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "//go:build !cuebootstrap\n\n")
	fmt.Fprintf(&buf, "package filetypes\n\n")

	if err := emitTagTypes(&buf, rootVal); err != nil {
		return err
	}
	// The registry is emitted first so that the aspect arrays its
	// entries share are all interned by the time they are declared.
	var registry bytes.Buffer
	if err := emitRegistry(&registry, rootVal); err != nil {
		return err
	}
	aspectSets.emit(&buf)
	buf.Write(registry.Bytes())

	data, err := goformat.Source(buf.Bytes())
	if err != nil {
		if err := os.WriteFile("types_gen.go", buf.Bytes(), 0o666); err != nil {
			return err
		}
		return fmt.Errorf("malformed source in types_gen.go: %v", err)
	}
	return os.WriteFile("types_gen.go", data, 0o666)
}

// emitTagTypes emits the built-in tag classification used by scope
// parsing, derived openly from the data: tagInfo keys are top-level
// tags; boolTags and tags keys anywhere are subsidiary tags.
func emitTagTypes(buf *bytes.Buffer, rootVal cue.Value) error {
	types := make(map[string]filetypes.TagType)
	add := func(name string, typ filetypes.TagType) error {
		if other, ok := types[name]; ok && other != typ {
			return fmt.Errorf("tag %q redefined with different type", name)
		}
		types[name] = typ
		return nil
	}
	addSubsidiary := func(v cue.Value) error {
		boolTags, err := structFields(lookup(v, "boolTags"))
		if err != nil {
			return fmt.Errorf("boolTags: %w", err)
		}
		for tagName := range boolTags {
			if err := add(tagName, filetypes.TagSubsidiaryBool); err != nil {
				return err
			}
		}
		tags, err := structFields(lookup(v, "tags"))
		if err != nil {
			return fmt.Errorf("tags: %w", err)
		}
		for tagName := range tags {
			if err := add(tagName, filetypes.TagSubsidiaryString); err != nil {
				return err
			}
		}
		return nil
	}
	tagInfo, err := structFieldsRequired(lookup(rootVal, "tagInfo"), "tagInfo")
	if err != nil {
		return err
	}
	for tagName, v := range tagInfo {
		if err := add(tagName, filetypes.TagTopLevel); err != nil {
			return err
		}
		if err := addSubsidiary(v); err != nil {
			return err
		}
	}
	interpretations, err := structFieldsRequired(lookup(rootVal, "interpretations"), "interpretations")
	if err != nil {
		return err
	}
	for _, v := range interpretations {
		if err := addSubsidiary(v); err != nil {
			return err
		}
	}
	forms, err := structFieldsRequired(lookup(rootVal, "forms"), "forms")
	if err != nil {
		return err
	}
	for _, v := range forms {
		if err := addSubsidiary(v); err != nil {
			return err
		}
	}

	fmt.Fprintf(buf, "func newTagTypes() map[string]TagType {\n")
	fmt.Fprintf(buf, "\treturn map[string]TagType{\n")
	for _, name := range slices.Sorted(maps.Keys(types)) {
		fmt.Fprintf(buf, "\t\t%q: %v,\n", name, types[name])
	}
	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "}\n\n")
	return nil
}

// emitRegistry extracts and emits the complete built-in registry data.
func emitRegistry(buf *bytes.Buffer, rootVal cue.Value) error {
	fmt.Fprintf(buf, "func newBuiltinRegistry() *registryData {\n")
	fmt.Fprintf(buf, "\treturn &registryData{\n")

	// Per-mode base FileInfo.
	fmt.Fprintf(buf, "\t\tbase: [NumModes]*entry{\n")
	for _, mode := range modeNames {
		e, err := extractEntry(lookup(rootVal, "modes", mode, "FileInfo"))
		if err != nil {
			return fmt.Errorf("modes.%s.FileInfo: %v", mode, err)
		}
		fmt.Fprintf(buf, "\t\t\t%s: ", modeConst(mode))
		emitEntry(buf, e, 3)
		fmt.Fprintf(buf, ",\n")
	}
	fmt.Fprintf(buf, "\t\t},\n")

	// Per-mode extension and encoding maps.
	for _, field := range []string{"extensions", "encodings"} {
		fmt.Fprintf(buf, "\t\t%s: [NumModes]map[string]*entry{\n", field)
		for _, mode := range modeNames {
			fmt.Fprintf(buf, "\t\t\t%s: {\n", modeConst(mode))
			if err := emitEntryMap(buf, lookup(rootVal, "modes", mode, field), 4); err != nil {
				return fmt.Errorf("modes.%s.%s: %v", mode, field, err)
			}
			fmt.Fprintf(buf, "\t\t\t},\n")
		}
		fmt.Fprintf(buf, "\t\t},\n")
	}

	// Global maps.
	for _, m := range []struct{ goField, cueField string }{
		{"tagInfo", "tagInfo"},
		{"forms", "forms"},
		{"interps", "interpretations"},
	} {
		fmt.Fprintf(buf, "\t\t%s: map[string]*entry{\n", m.goField)
		if err := emitEntryMap(buf, lookup(rootVal, m.cueField), 3); err != nil {
			return fmt.Errorf("%s: %v", m.cueField, err)
		}
		fmt.Fprintf(buf, "\t\t},\n")
	}

	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "}\n")
	return nil
}

func modeConst(mode string) string {
	switch mode {
	case "input":
		return "Input"
	case "export":
		return "Export"
	case "def":
		return "Def"
	case "eval":
		return "Eval"
	}
	panic("unknown mode " + mode)
}

func emitEntryMap(buf *bytes.Buffer, v cue.Value, depth int) error {
	fields, err := structFieldsRequired(v, v.Path().String())
	if err != nil {
		return err
	}
	indent := strings.Repeat("\t", depth)
	for _, name := range slices.Sorted(maps.Keys(fields)) {
		e, err := extractEntry(fields[name])
		if err != nil {
			return fmt.Errorf("%s: %v", name, err)
		}
		fmt.Fprintf(buf, "%s%q: ", indent, name)
		emitEntry(buf, e, depth)
		fmt.Fprintf(buf, ",\n")
	}
	return nil
}

// emitEntry writes an entry composite literal. Inside a []*entry or
// map[string]*entry composite the &entry{...} form elides to {...},
// but alts elements need the explicit form only when standalone; we
// always emit plain {...} literals valid in pointer composites.
func emitEntry(buf *bytes.Buffer, e *entry, depth int) {
	indent := strings.Repeat("\t", depth)
	fmt.Fprintf(buf, "{\n")
	if len(e.alts) > 0 {
		fmt.Fprintf(buf, "%s\talts: []*entry{\n", indent)
		for _, alt := range e.alts {
			fmt.Fprintf(buf, "%s\t\t", indent)
			emitEntry(buf, alt, depth+2)
			fmt.Fprintf(buf, ",\n")
		}
		fmt.Fprintf(buf, "%s\t},\n", indent)
		fmt.Fprintf(buf, "%s}", indent)
		return
	}
	if s := svalExpr(e.encoding); s != "" {
		fmt.Fprintf(buf, "%s\tencoding: %s,\n", indent, s)
	}
	if s := svalExpr(e.interpretation); s != "" {
		fmt.Fprintf(buf, "%s\tinterpretation: %s,\n", indent, s)
	}
	if s := svalExpr(e.form); s != "" {
		fmt.Fprintf(buf, "%s\tform: %s,\n", indent, s)
	}
	if s := aspectSets.intern(e.aspects); s != "" {
		fmt.Fprintf(buf, "%s\taspects: %s,\n", indent, s)
	}
	if len(e.boolTags) > 0 {
		fmt.Fprintf(buf, "%s\tboolTags: map[string]bval{\n", indent)
		for _, name := range slices.Sorted(maps.Keys(e.boolTags)) {
			fmt.Fprintf(buf, "%s\t\t%q: %s,\n", indent, name, elideType(bvalExpr(e.boolTags[name])))
		}
		fmt.Fprintf(buf, "%s\t},\n", indent)
	}
	if len(e.tags) > 0 {
		fmt.Fprintf(buf, "%s\ttags: map[string]sval{\n", indent)
		for _, name := range slices.Sorted(maps.Keys(e.tags)) {
			fmt.Fprintf(buf, "%s\t\t%q: %s,\n", indent, name, elideType(svalExpr(e.tags[name])))
		}
		fmt.Fprintf(buf, "%s\t},\n", indent)
	}
	fmt.Fprintf(buf, "%s}", indent)
}

func aspectConst(name string) string {
	return "a" + strings.ToUpper(name[:1]) + name[1:]
}

// aspectSets interns the aspect arrays of every emitted entry. The
// built-in entries hold only a handful of distinct aspect
// combinations between them, so naming each one once and referring to
// it keeps both the generated code and the data it builds small.
var aspectSets aspectSetTable

type aspectSetTable struct {
	names map[string]string // literal -> variable name
	order []string          // literals, in first-seen order
}

// intern returns the name of the variable holding aspects, declaring a
// new one if this combination has not been seen. It returns the empty
// string if every aspect is unset, in which case the entry's zero
// value already says the same thing.
func (t *aspectSetTable) intern(aspects map[string]bval) string {
	var lit strings.Builder
	lit.WriteString("[numAspects]bval{")
	first := true
	for _, name := range aspectNames {
		s := bvalExpr(aspects[name])
		if s == "" {
			continue
		}
		if !first {
			lit.WriteString(", ")
		}
		first = false
		fmt.Fprintf(&lit, "%s: %s", aspectConst(name), s)
	}
	lit.WriteString("}")
	if first {
		return ""
	}
	key := lit.String()
	if name, ok := t.names[key]; ok {
		return name
	}
	name := fmt.Sprintf("aspectSet%d", len(t.order))
	if t.names == nil {
		t.names = make(map[string]string)
	}
	t.names[key] = name
	t.order = append(t.order, key)
	return name
}

// emit writes the declarations for every interned aspect array. It
// must run after the entries that refer to them have been emitted.
func (t *aspectSetTable) emit(buf *bytes.Buffer) {
	if len(t.order) == 0 {
		return
	}
	fmt.Fprintf(buf, "// Aspect combinations shared by the entries below.\nvar (\n")
	for _, key := range t.order {
		fmt.Fprintf(buf, "\t%s = %s\n", t.names[key], key)
	}
	fmt.Fprintf(buf, ")\n\n")
}

// svalExpr and bvalExpr emit struct literals rather than calls to the
// sval and bval constructors in unify.go. A call cannot be folded at
// compile time, so every one of the hundreds of values here would
// otherwise have to be built by instructions at run time; literals let
// the compiler lay the shared aspect arrays out as static data.

func svalExpr(v sval) string {
	switch v.kind {
	case unset:
		return ""
	case constraint:
		if v.domain != nil {
			return fmt.Sprintf("sval{kind: constraint, domain: %s}", stringSlice(v.domain))
		}
		return fmt.Sprintf("sval{kind: constraint, excluded: %s}", stringSlice(v.excluded))
	case dflt:
		switch {
		case len(v.excluded) != 0:
			return fmt.Sprintf("sval{kind: dflt, value: %q, excluded: %s}", v.value, stringSlice(v.excluded))
		case v.domain != nil:
			return fmt.Sprintf("sval{kind: dflt, value: %q, domain: %s}", v.value, stringSlice(v.domain))
		}
		return fmt.Sprintf("sval{kind: dflt, value: %q}", v.value)
	default:
		return fmt.Sprintf("sval{kind: concrete, value: %q}", v.value)
	}
}

func bvalExpr(v bval) string {
	switch v.kind {
	case unset:
		return ""
	case dflt:
		if v.value {
			return "dtrue"
		}
		return "dfalse"
	case ref:
		return fmt.Sprintf("bval{kind: ref, reference: %q}", v.reference)
	default:
		if v.value {
			return "ctrue"
		}
		return "cfalse"
	}
}

// elideType drops the type name from a composite literal, as is
// required of a value inside a map or slice literal of that same type
// for the result to be gofmt -s clean. Values that are not composite
// literals, such as the shared bvals, are returned unchanged.
func elideType(lit string) string {
	if i := strings.IndexByte(lit, '{'); i >= 0 {
		return lit[i:]
	}
	return lit
}

func stringSlice(ss []string) string {
	args := make([]string, len(ss))
	for i, s := range ss {
		args[i] = fmt.Sprintf("%q", s)
	}
	return fmt.Sprintf("[]string{%s}", strings.Join(args, ", "))
}

// extractEntry converts one evaluated #FileInfo-shaped CUE value into
// the open representation, preserving default-ness per field. A
// struct-level disjunction (tagInfo.pb, input-mode encodings.cue)
// becomes an entry whose alts list the disjuncts, default first.
//
// The disjunction is not necessarily the top-level operation: the value
// usually presents as a conjunction of the disjunction with contextual
// constraints such as "[_]: #FileInfo". findDisjunction locates it, and
// the default disjunct is extracted from v.Default(), which resolves
// the disjunction to its default while retaining those contextual
// conjuncts. The raw disjuncts lack that context; the mode base entry
// carries the same #FileInfo defaults, so nothing is lost at
// resolution time. The default may appear again among the raw
// disjuncts; a duplicate alternative is harmless (it is only retried
// on backtracking and fails identically).
func extractEntry(v cue.Value) (*entry, error) {
	if !v.Exists() {
		return nil, fmt.Errorf("entry does not exist")
	}
	if err := v.Validate(); err != nil {
		return nil, fmt.Errorf("invalid entry: %w", err)
	}
	if args, ok := findDisjunction(v); ok {
		d, hasDefault := v.Default()
		if !hasDefault {
			return nil, fmt.Errorf("struct disjunction without default")
		}
		de, err := extractEntryStruct(d)
		if err != nil {
			return nil, err
		}
		e := &entry{alts: []*entry{de}}
		for _, a := range args {
			alt, err := extractEntryStruct(a)
			if err != nil {
				return nil, err
			}
			e.alts = append(e.alts, alt)
		}
		return e, nil
	}
	return extractEntryStruct(v)
}

// findDisjunction reports the disjuncts of the struct-level disjunction
// embedded in v, looking through conjunction operands. types.cue holds
// at most one struct-level disjunction per entry value. A disjunction
// whose disjuncts contain references (input-mode "encodings: cue:
// *forms.schema | _") is not decomposed by Expr on the raw value; Eval
// exposes it, with the sibling conjuncts folded into each disjunct.
func findDisjunction(v cue.Value) ([]cue.Value, bool) {
	if args, ok := findDisjunctionExpr(v); ok {
		return args, true
	}
	if v.Kind() == cue.BottomKind && v.Exists() {
		if _, hasDefault := v.Default(); hasDefault {
			return findDisjunctionExpr(v.Eval())
		}
	}
	return nil, false
}

func findDisjunctionExpr(v cue.Value) ([]cue.Value, bool) {
	switch op, args := v.Expr(); op {
	case cue.OrOp:
		if len(args) > 1 {
			return args, true
		}
	case cue.AndOp:
		for _, a := range args {
			if alts, ok := findDisjunctionExpr(a); ok {
				return alts, ok
			}
		}
	}
	return nil, false
}

// extractEntryStruct extracts a plain (non-disjunctive) entry value
// field by field.
func extractEntryStruct(v cue.Value) (*entry, error) {
	fields, err := structFieldsRequired(v, v.Path().String())
	if err != nil {
		return nil, err
	}
	allowed := supportedFileInfoFields()
	for name := range fields {
		if !allowed[name] {
			return nil, fmt.Errorf("unsupported #FileInfo field %q", name)
		}
	}

	e := &entry{}
	err = nil
	if e.encoding, err = extractStr(v, "encoding"); err != nil {
		return nil, err
	}
	if e.interpretation, err = extractStr(v, "interpretation"); err != nil {
		return nil, err
	}
	if e.form, err = extractStr(v, "form"); err != nil {
		return nil, err
	}
	e.aspects = map[string]bval{}
	for _, name := range aspectNames {
		b, err := extractBool(v, name, nil)
		if err != nil {
			return nil, err
		}
		if b.kind != unset {
			e.aspects[name] = b
		}
	}
	bt := lookup(v, "boolTags")
	if bt.Exists() {
		fields, err := structFields(bt)
		if err != nil {
			return nil, fmt.Errorf("boolTags: %w", err)
		}
		names := slices.Sorted(maps.Keys(fields))
		e.boolTags = map[string]bval{}
		for _, name := range names {
			b, err := extractBool(bt, name, names)
			if err != nil {
				return nil, err
			}
			e.boolTags[name] = b
		}
	}
	st := lookup(v, "tags")
	if st.Exists() {
		fields, err := structFields(st)
		if err != nil {
			return nil, fmt.Errorf("tags: %w", err)
		}
		e.tags = map[string]sval{}
		for name := range fields {
			s, err := extractStr(st, name)
			if err != nil {
				return nil, err
			}
			e.tags[name] = s
		}
	}
	return e, nil
}

func extractStr(v cue.Value, field string) (sval, error) {
	f := lookup(v, field)
	if !f.Exists() {
		return sval{}, nil
	}
	if err := f.Validate(); err != nil {
		return sval{}, fmt.Errorf("%s: invalid string field: %w", field, err)
	}
	if d, ok := f.Default(); ok {
		s, err := d.String()
		if err != nil {
			return sval{}, fmt.Errorf("%s: default is not a concrete string: %w", field, err)
		}
		if f.IsConcrete() && f.Kind() == cue.StringKind {
			return sval{kind: concrete, value: s}, nil
		}
		value, err := extractDefaultStr(f, s)
		if err != nil {
			return sval{}, fmt.Errorf("%s: %w", field, err)
		}
		return value, nil
	}
	if f.IsConcrete() && f.Kind() == cue.StringKind {
		s, err := f.String()
		if err != nil {
			return sval{}, err
		}
		return sval{kind: concrete, value: s}, nil
	}
	c, err := extractStrConstraint(f)
	if err != nil {
		return sval{}, fmt.Errorf("%s: %w", field, err)
	}
	return c, nil
}

// extractStrConstraint recognizes every non-default string constraint the
// driver can represent. Mutual subsumption is intentional: checking only
// IncompleteKind would silently accept a future regex or bound as generic
// string and discard its semantics.
func extractStrConstraint(f cue.Value) (sval, error) {
	if args, ok := findDisjunction(f.Eval()); ok {
		set := make(map[string]bool, len(args))
		for _, a := range args {
			if !a.IsConcrete() || a.Kind() != cue.StringKind {
				return sval{}, fmt.Errorf("unsupported non-default string disjunction")
			}
			s, err := a.String()
			if err != nil {
				return sval{}, fmt.Errorf("reading string constraint disjunct: %w", err)
			}
			set[s] = true
		}
		if len(set) == 0 {
			return sval{}, fmt.Errorf("empty string constraint disjunction")
		}
		return sval{kind: constraint, domain: slices.Sorted(maps.Keys(set))}, nil
	}
	for _, expr := range []string{"_", "string"} {
		if equivalentValue(f, f.Context().CompileString(expr)) {
			return sval{}, nil
		}
	}
	for value, expr := range map[string]string{
		"":         `string & !=""`,
		"binarypb": `string & !="binarypb"`,
	} {
		if equivalentValue(f, f.Context().CompileString(expr)) {
			return sval{kind: constraint, excluded: []string{value}}, nil
		}
	}
	return sval{}, fmt.Errorf("unsupported non-default string constraint %s", syntaxString(f))
}

func equivalentValue(a, b cue.Value) bool {
	a = a.Eval()
	b = b.Eval()
	return a.Subsume(b, cue.Raw()) == nil && b.Subsume(a, cue.Raw()) == nil
}

// extractDefaultStr recognizes every defaulted string shape the driver
// can represent. Whole-value semantic checks come first because CUE may
// present a disjunction conjoined with a named constraint (for example,
// (*"cue" | _) & #Encoding) without exposing that disjunction through
// Value.Expr. Mutual subsumption ensures regexes and bounds are not
// mistaken for generic string constraints.
func extractDefaultStr(f cue.Value, defaultValue string) (sval, error) {
	quoted := fmt.Sprintf("%q", defaultValue)
	for _, candidate := range []struct {
		expr     string
		excluded []string
	}{
		{expr: "*" + quoted + " | _"},
		{expr: "*" + quoted + " | string"},
		{expr: "(*" + quoted + ` | _) & !=""`, excluded: []string{""}},
		{expr: "(*" + quoted + ` | string) & !=""`, excluded: []string{""}},
		{expr: "(*" + quoted + ` | _) & !="binarypb"`, excluded: []string{"binarypb"}},
		{expr: "(*" + quoted + ` | string) & !="binarypb"`, excluded: []string{"binarypb"}},
	} {
		if equivalentValue(f, f.Context().CompileString(candidate.expr)) {
			return sval{kind: dflt, value: defaultValue, excluded: candidate.excluded}, nil
		}
	}

	args, ok := findDisjunction(f.Eval())
	if !ok {
		return sval{}, fmt.Errorf("unsupported defaulted string constraint %s", syntaxString(f))
	}
	set := map[string]bool{}
	for _, a := range args {
		if err := a.Validate(); err != nil {
			return sval{}, fmt.Errorf("invalid string disjunct: %w", err)
		}
		if !a.IsConcrete() || a.Kind() != cue.StringKind {
			return sval{}, fmt.Errorf("unsupported string disjunct %s", syntaxString(a))
		}
		s, err := a.String()
		if err != nil {
			return sval{}, fmt.Errorf("reading string disjunct: %w", err)
		}
		set[s] = true
	}
	if len(set) == 0 {
		return sval{}, fmt.Errorf("string disjunction has no concrete alternatives")
	}
	return sval{kind: dflt, value: defaultValue, domain: slices.Sorted(maps.Keys(set))}, nil
}

// extractBool extracts a tri-state boolean. When siblings is non-nil
// (subsidiary boolTags extraction), a default that references a
// sibling tag — "strictKeywords: *strict | bool" — is detected from
// the raw syntax and recorded as a ref value.
func extractBool(v cue.Value, field string, siblings []string) (bval, error) {
	f := lookup(v, field)
	if !f.Exists() {
		return bval{}, nil
	}
	if err := f.Validate(); err != nil {
		return bval{}, fmt.Errorf("%s: invalid boolean field: %w", field, err)
	}
	if siblings != nil {
		if target, ok := refDefault(f.Syntax(cue.Raw())); ok {
			if !slices.Contains(siblings, target) {
				return bval{}, fmt.Errorf("%s: default references unknown tag %q", field, target)
			}
			d, hasDefault := f.Default()
			if !hasDefault {
				return bval{}, fmt.Errorf("%s: reference default has no default value", field)
			}
			b, err := d.Bool()
			if err != nil || !isSupportedDefaultBool(f, b) {
				return bval{}, fmt.Errorf("%s: unsupported reference-default boolean constraint %s", field, syntaxString(f))
			}
			return bval{kind: ref, reference: target}, nil
		}
	}
	if d, ok := f.Default(); ok {
		b, err := d.Bool()
		if err != nil {
			return bval{}, fmt.Errorf("%s: default is not a concrete boolean: %w", field, err)
		}
		if f.IsConcrete() && f.Kind() == cue.BoolKind {
			return bval{kind: concrete, value: b}, nil
		}
		if !isSupportedDefaultBool(f, b) {
			return bval{}, fmt.Errorf("%s: unsupported defaulted boolean constraint %s", field, syntaxString(f))
		}
		return bval{kind: dflt, value: b}, nil
	}
	if f.IsConcrete() && f.Kind() == cue.BoolKind {
		b, err := f.Bool()
		if err != nil {
			return bval{}, err
		}
		return bval{kind: concrete, value: b}, nil
	}
	for _, expr := range []string{"_", "bool"} {
		if equivalentValue(f, f.Context().CompileString(expr)) {
			return bval{}, nil
		}
	}
	return bval{}, fmt.Errorf("%s: unsupported non-concrete boolean constraint %s", field, syntaxString(f))
}

func isSupportedDefaultBool(v cue.Value, defaultValue bool) bool {
	other := !defaultValue
	for _, expr := range []string{
		fmt.Sprintf("*%t | %t", defaultValue, other),
		fmt.Sprintf("*%t | bool", defaultValue),
	} {
		if equivalentValue(v, v.Context().CompileString(expr)) {
			return true
		}
	}
	return false
}

func syntaxString(v cue.Value) string {
	b, err := cueformat.Node(v.Syntax(cue.Raw()))
	if err != nil {
		return fmt.Sprint(v.Syntax(cue.Raw()))
	}
	return string(b)
}

// refDefault reports whether the raw syntax of a field contains a
// default marker referencing an identifier, as in "*strict | bool"
// (possibly wrapped in conjunctions from unification).
func refDefault(n ast.Node) (string, bool) {
	switch x := n.(type) {
	case *ast.ParenExpr:
		return refDefault(x.X)
	case *ast.BinaryExpr:
		if x.Op == token.OR || x.Op == token.AND {
			if name, ok := refDefault(x.X); ok {
				return name, true
			}
			return refDefault(x.Y)
		}
	case *ast.UnaryExpr:
		if x.Op == token.MUL {
			if id, ok := x.X.(*ast.Ident); ok {
				return id.Name, true
			}
		}
	}
	return "", false
}

// structFields collects the regular fields of v. Unlike the previous
// iterator wrapper, it propagates iteration errors so generation cannot
// silently turn an invalid value into an empty table.
func structFields(v cue.Value, opts ...cue.Option) (map[string]cue.Value, error) {
	if !v.Exists() {
		return nil, nil
	}
	iter, err := v.Fields(opts...)
	if err != nil {
		return nil, err
	}
	fields := make(map[string]cue.Value)
	for iter.Next() {
		fields[iter.Selector().Unquoted()] = iter.Value()
	}
	return fields, nil
}

func structFieldsRequired(v cue.Value, name string) (map[string]cue.Value, error) {
	if !v.Exists() {
		return nil, fmt.Errorf("required value %s does not exist", name)
	}
	fields, err := structFields(v)
	if err != nil {
		return nil, fmt.Errorf("iterating %s: %w", name, err)
	}
	if len(fields) == 0 {
		return nil, fmt.Errorf("required value %s has no fields", name)
	}
	return fields, nil
}

func supportedFileInfoFields() map[string]bool {
	fields := map[string]bool{
		"filename": true, "encoding": true, "interpretation": true,
		"form": true, "tags": true, "boolTags": true,
	}
	for _, name := range aspectNames {
		fields[name] = true
	}
	return fields
}

// validateFileInfoSchema makes the duplicated driver field list an
// explicit checked contract. Optional fields must be included here: a new
// optional #FileInfo field may be absent from every current entry and would
// otherwise be silently omitted by per-entry validation.
func validateFileInfoSchema(root cue.Value) error {
	v := root.LookupPath(cue.MakePath(cue.Def("#FileInfo")))
	fields, err := structFieldsRequired(v, "#FileInfo")
	if err != nil {
		return err
	}
	optional, err := structFields(v, cue.Optional(true))
	if err != nil {
		return fmt.Errorf("iterating optional #FileInfo fields: %w", err)
	}
	for name, value := range optional {
		fields[name] = value
	}
	want := supportedFileInfoFields()
	for name := range fields {
		if !want[name] {
			return fmt.Errorf("#FileInfo has unsupported field %q", name)
		}
		delete(want, name)
	}
	if len(want) != 0 {
		return fmt.Errorf("#FileInfo is missing supported fields %v", slices.Sorted(maps.Keys(want)))
	}
	return nil
}

// validateExtractorGuards keeps the generator's fail-closed cases live in
// every go generate invocation even though this build-ignored program
// cannot have ordinary package tests beside package filetypes.
func validateExtractorGuards(ctx *cue.Context) error {
	for _, tc := range []struct {
		field string
		src   string
		bool  bool
	}{
		{field: "form", src: `{form: =~"x"}`},
		{field: "form", src: `{form: >"x"}`},
		{field: "form", src: `{form: *"x" | =~"x"}`},
		{field: "form", src: `{form: *1 | string}`},
		{field: "data", src: `{data: *"x" | bool}`, bool: true},
		{field: "data", src: `{data: *true | int}`, bool: true},
	} {
		v := ctx.CompileString(tc.src)
		var err error
		if tc.bool {
			_, err = extractBool(v, tc.field, nil)
		} else {
			_, err = extractStr(v, tc.field)
		}
		if err == nil {
			return fmt.Errorf("internal generator check: unsupported shape %s was accepted", tc.src)
		}
	}
	if _, err := extractEntryStruct(ctx.CompileString(`{surprise: true}`)); err == nil {
		return fmt.Errorf("internal generator check: unsupported #FileInfo field was accepted")
	}
	return nil
}

func lookup(v cue.Value, elems ...string) cue.Value {
	sels := make([]cue.Selector, len(elems))
	for i := range elems {
		sels[i] = cue.Str(elems[i])
	}
	return v.LookupPath(cue.MakePath(sels...))
}
